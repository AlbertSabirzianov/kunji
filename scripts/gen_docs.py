def gen_providers() -> None:
    out_dir = DOCS / "providers"
    for f in out_dir.glob("*.md"):
        if f.name != "index.md":
            f.unlink()
    out_dir.mkdir(parents=True, exist_ok=True)
    for i, spec in enumerate(BUILTIN.values()):
        kind = ("Runs locally, no key" if not spec.needs_key else
                "Anthropic API" if spec.kind == "anthropic" else "OpenAI-compatible API")
        title = f"Use {spec.name} in your terminal"
        desc = (f"Chat with {spec.name} models from the command line with kunji: "
                f"set up your API key, pick a model and start chatting.")
        steps = []
        if spec.needs_key:
            steps += [f"1. Create an API key at [{spec.key_url}]({spec.key_url}).",
                      f"2. Run `kunji keys add {spec.id}` and paste the key. kunji checks it "
                      "works, then stores it in your OS keychain.",
                      "3. Pick a default model from the list (type to search).",
                      "4. Run `kunji` and start chatting."]
        else:
            steps += [f"1. Install Ollama from [{spec.key_url}]({spec.key_url}) and download a "
                      "model, for example `ollama pull llama3.2`.",
                      f"2. Run `kunji keys add {spec.id}`. No key is needed; kunji connects to "
                      "Ollama on your computer.",
                      "3. Pick the model you downloaded.",
                      "4. Run `kunji` and start chatting."]
        facts = [["Provider id", f"`{spec.id}`"], ["Type", kind],
                 ["API address", f"`{spec.base_url}`"]]
        if spec.env_vars:
            facts.append(["Key variable", " or ".join(f"`{e}`" for e in spec.env_vars)])
        body = [frontmatter(title, desc, order=i + 1, label=spec.name),
                PROVIDER_NOTES.get(spec.id, f"Use {spec.name} models with your own key. You pay "
                                   f"{spec.name} directly; kunji never sees your bill."), "",
                "## Set up", "", *steps, "",
                "## Details", "", table(["", ""], facts), "",
                "## Use it", "",
                "```bash", f"kunji models {spec.id}            # see available models",
                f"kunji use {spec.id}:<model>        # make one your default",
                f"kunji chat -m {spec.id}:<model>    # or chat with it once",
                "```", "",
                f"Inside a chat, switch to it with `/model {spec.id}:<model>`; the "
                "conversation carries over.", ""]
        if spec.needs_key and spec.env_vars:
            body += ["## Use an environment variable instead", "",
                     "For CI or scripts you can skip the keychain:", "",
                     "```bash", f"export {spec.env_vars[0]}=your-key-here", "kunji ask "
                     f'-m {spec.id}:<model> "Hello"', "```", ""]
        (out_dir / f"{spec.id}.md").write_text("\n".join(body), encoding="utf-8")


def gen_changelog() -> None:
    text = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    text = re.sub(r"^# Changelog\s*\n", "", text).strip()
    text = re.sub(r"## \[Unreleased\]\s*\n(?=## )", "", text)
    text = re.sub(r"^## \[([^\]]+)\] - (\S+)", r"## \1 (\2)", text, flags=re.M)
    text = text.replace("### ", "#### ")
    body = [frontmatter("Changelog", "What's new in every kunji release.", order=1),
            "Every release with its changes, newest first. Downloads are on the "
            "[GitHub releases page](https://github.com/testwithsuraj/kunji/releases).", "",
            "To update kunji, run `kunji upgrade` (or `pip install --upgrade kunji`).", "",
            text, ""]
    out = DOCS / "releases"
    out.mkdir(parents=True, exist_ok=True)
    (out / "changelog.md").write_text("\n".join(body), encoding="utf-8")


def main() -> int:
    gen_cli()
    gen_chat_commands()
    gen_env_vars()
    gen_providers()
    gen_changelog()
    print("docs generated in", DOCS.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
