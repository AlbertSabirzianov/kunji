_MARKUP = re.compile(r"\[(?:/|dim|bold|italic|cyan|green|red)[^\]]*\]")


def clean(text: str | None) -> str:
    return _MARKUP.sub("", text or "").strip()


def frontmatter(title: str, description: str, order: int | None = None,
                label: str | None = None) -> str:
    lines = ["---", f"title: {json.dumps(title)}", f"description: {json.dumps(description)}",
             "editUrl: false"]
    if order is not None or label:
        lines.append("sidebar:")
        if order is not None:
            lines.append(f"  order: {order}")
        if label:
            lines.append(f"  label: {json.dumps(label)}")
    lines.append("---")
    return "\n".join(lines) + "\n\n" + GENERATED + "\n"


def md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def arg_name(p) -> str:
    name = (
        getattr(p, "human_readable_name", None)
        or getattr(p, "name", None)
        or getattr(p, "metavar", None)
        or "arg"
    )
    if callable(name):
        name = name()
    return str(name).lower()


def param_rows(cmd) -> tuple[list[list[str]], list[list[str]]]:
    args, opts = [], []
    for p in cmd.params:
        if getattr(p, "hidden", False) or getattr(p, "name", None) in ("help",):
            continue
        help_text = md_escape(clean(getattr(p, "help", "") or ""))
        if getattr(p, "param_type_name", None) == "argument":
            name = arg_name(p)
            args.append([f"`{name}`", "yes" if getattr(p, "required", False) else "no", help_text or "—"])
        else:
            flags = ", ".join(f"`{o}`" for o in [*getattr(p, "opts", []), *getattr(p, "secondary_opts", [])])
            default = ""
            default_val = getattr(p, "default", None)
            if not getattr(p, "is_flag", False) and default_val not in (None, "", (), []):
                default = f" (default: `{default_val}`)"
            opts.append([flags, (help_text or "—") + default])
    return args, opts


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def usage_line(path: str, cmd) -> str:
    parts = [path]
    for p in cmd.params:
        if getattr(p, "param_type_name", None) == "argument":
            name = arg_name(p)
            parts.append(f"<{name}>" if getattr(p, "required", False) else f"[{name}]")
    if any(getattr(p, "param_type_name", None) == "option" and getattr(p, "name", None) != "help" for p in cmd.params):
        parts.append("[options]")
    return " ".join(parts)


def command_section(path: str, cmd, level: str = "##") -> str:
    out = [f"{level} {path}", "", clean(cmd.help).split("\n\n")[0], "",
           "```bash", usage_line(path, cmd), "```", ""]
    args, opts = param_rows(cmd)
    if args:
        out += ["**Arguments**", "", table(["Name", "Required", "Description"], args), ""]
    if opts:
        out += ["**Options**", "", table(["Option", "Description"], opts), ""]
    return "\n".join(out)


def gen_cli() -> None:
    root = typer.main.get_command(app)
    assert hasattr(root, "commands")
    out_dir = DOCS / "reference" / "cli"
    shutil.rmtree(out_dir, ignore_errors=True)
    out_dir.mkdir(parents=True)
    names = [n for n in ORDER if n in root.commands]
    names += sorted(n for n, c in root.commands.items() if n not in names and not c.hidden)
    index_rows = []
    for i, name in enumerate(names):
        cmd = root.commands[name]
        if cmd.hidden:
            continue
        desc = DESCRIPTIONS.get(name, clean(cmd.help).split("\n")[0])
        index_rows.append([f"[`kunji {name}`]({BASE}/reference/cli/{name}/)", md_escape(desc)])
        body = [frontmatter(f"kunji {name}", desc, order=i + 1, label=f"kunji {name}"),
                desc, ""]
        if EXAMPLES.get(name):
            body += ["## Examples", "", "```bash"]
            for n, (label, example) in enumerate(EXAMPLES[name]):
                body += ([""] if n else []) + [f"# {label}", example]
            body += ["```", ""]
        if hasattr(cmd, "commands"):
            if getattr(cmd, "invoke_without_command", False):
                body += [command_section(f"kunji {name}", cmd)]
            for sub_name, sub in cmd.commands.items():
                if not sub.hidden:
                    body += [command_section(f"kunji {name} {sub_name}", sub)]
        else:
            body += ["## Usage", "", command_section(f"kunji {name}", cmd, level="###")]
        body += ["", "Run `kunji " + name + " --help` in your terminal to see this in place."]
        (out_dir / f"{name}.md").write_text("\n".join(body).rstrip() + "\n", encoding="utf-8")

    # The @prompt shortcut is not a Typer command, document it on the overview.
    index_rows.insert(3, [f"[`kunji @name`]({BASE}/guides/saved-prompts/)",
                          "Run a saved prompt, e.g. `kunji @commit`"])
    overview = [frontmatter("Command reference", "Every kunji command, option and argument.",
                            order=0, label="Overview"),
                "Run `kunji` on its own to open the interactive menu. Every action in the menu "
                "is also a command, listed below. Add `--help` to any command to see its options "
                "in the terminal.", "",
                table(["Command", "What it does"], index_rows), "",
                f"Inside a chat you can also type slash commands; see "
                f"[Chat commands]({BASE}/reference/chat-commands/)."]
    (out_dir / "index.md").write_text("\n".join(overview) + "\n", encoding="utf-8")


def gen_chat_commands() -> None:
    rows = [[f"`{cmd}`", md_escape(desc)] for cmd, desc in SLASH_COMMANDS.items()]
    rows.insert(5, ["`@name text`", "Use a saved prompt, e.g. `@explain this error`"])
    keys = [["Enter", "Send your message"], ["Alt+Enter or Ctrl+J", "New line"],
            ["Tab", "Complete commands, model names, prompt names and file paths"],
            ["↑ / ↓", "Previous / next message you typed"],
            ["Ctrl+C", "Stop the answer that is being written"],
            ["Ctrl+D", "Leave the chat (back to the menu if you came from it)"]]
    body = [frontmatter("Chat commands", "Slash commands and keyboard shortcuts inside a kunji "
                        "chat.", order=20),
            "Type these inside `kunji chat` (or a chat started from the menu).", "",
            "## Slash commands", "", table(["Type", "What it does"], rows), "",
            "## Keyboard shortcuts", "", table(["Key", "Action"], keys), ""]
    (DOCS / "reference" / "chat-commands.md").write_text("\n".join(body), encoding="utf-8")


def gen_env_vars() -> None:
    rows = []
    for spec in BUILTIN.values():
        names = [*spec.env_vars, f"KUNJI_{spec.id.upper()}_API_KEY"] if spec.needs_key else []
        if names:
            rows.append([spec.name, " or ".join(f"`{n}`" for n in names)])
    other = [["`KUNJI_<ID>_API_KEY`", "Key for any provider, including custom ones, e.g. "
                                     "`KUNJI_LMSTUDIO_API_KEY`"],
             ["`KUNJI_HOME`", "Keep config, data and cache in one folder (handy for testing)"],
             ["`NO_COLOR`", "Turn off colours"]]
    body = [frontmatter("Environment variables", "Environment variables kunji reads, including "
                        "API keys for every provider.", order=40),
            "Environment variables override keys stored in the keychain, which makes them handy "
            "for CI and scripts.", "",
            "## Provider keys", "", table(["Provider", "Variable"], rows), "",
            "## Other variables", "", table(["Variable", "Purpose"], other), ""]
    (DOCS / "reference" / "environment-variables.md").write_text("\n".join(body),
                                                                 encoding="utf-8")


